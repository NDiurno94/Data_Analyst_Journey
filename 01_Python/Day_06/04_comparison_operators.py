"""Comparisons produce True or False.
== means equal; != means not equal.
>= and <= include the boundary value."""

age = 32
print(age == 32)  # True
print(age != 32)  # False
print(age > 18)   # True
print(age < 18)   # False
print(age >= 32)  # True
print(age <= 32)  # True
print(18 <= age < 65)  # True: age is at least 18 and below 65



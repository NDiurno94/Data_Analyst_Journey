# Python Indentation Example

if 5 > 2:
    print("Five is greater than two!")  

# if 5 > 2:
# print("Five is greater than two!")

'''Indentation is very important in Python. It is used to define the blocks of code. 
In the above example, the print statement is indented, which means it is part of the if statement block. 
If you remove the indentation, it will result in an error.
You have to use the same number of spaces in the same block of code, 
otherwise Python will give you an error'''

#Python Variables Example

age = 30
y = "Hello, World!"

print(age)
print(y)
print("The value of age is:", age)
print("The statement of y is:", y)
print("The sum of age and 10 is:", age + 10)

'''In the above example, we have defined two variables age and y.
age is assigned the value 30, and y is assigned the string "Hello, World!"
We then print the values of age and y, as well as some additional statements that include 
the values of these variables.
You can use variables to store data and perform operations on them.'''

# Python Statements Example

print("This is a statement in Python.")
print("You can have multiple statements on the same line using a semicolon") ; print("This is another statement.")
print("Hello World!", end=' ') ; print("This is a statement that continues on the same line.")

'''In the above example, we have used the print() function to display statements in Python.
We have also demonstrated that you can have multiple statements on the same line using a semicolon.'''

# Python Numbers Example

print(3)
print(3.14)
print(-5)

# we can also do math inside the print statement
print("The sum of 3 and 5 is:", 3 + 5)
print("The product of 3 and 4 is:", 3 * 4)

# we can mix numbers and words in the print statement
print("I am", 25 + 5, "years old.")

'''In the above example, we have printed different types of numbers in Python, 
including integers and floating-point numbers.
We have also demonstrated that we can perform mathematical operations inside the print 
statement, and we can mix numbers and words in the same print statement.'''